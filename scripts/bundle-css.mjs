async function bundle(options = {}) {
    const quiet = options.quiet || process.argv.includes('--quiet');
    
    if (!quiet) console.log('Bundling CSS...');
    
    // Build absolute, deduped file list
    const inputPaths = Array.from(
        new Set(
            files.map(f => path.join(stylesDir, f))
        )
    );

    // Guard: ensure output is not among inputs
    const outputPath = outputFile;
    const filteredInputs = inputPaths.filter(p => path.resolve(p) !== path.resolve(outputPath));

    let bundleContent = '';

    // Add a header
    bundleContent += '/* \n';
    bundleContent += ' * RADIAL TIMELINE STYLES\n';
    bundleContent += ' * Auto-generated from src/styles/*.css\n';
    bundleContent += ' * Do not edit this file directly. Edit the files in src/styles/ instead.\n';
    bundleContent += ' */\n\n';

    for (const filePath of filteredInputs) {
        if (fs.existsSync(filePath)) {
            const content = embedBundledFontUrls(fs.readFileSync(filePath, 'utf-8'));
            bundleContent += `/* --- ${path.relative(stylesDir, filePath)} --- */\n`;
            bundleContent += content;
            bundleContent += '\n\n';
        } else {
            console.warn(`Warning: ${path.relative(stylesDir, filePath)} not found in ${stylesDir}`);
        }
    }

    fs.writeFileSync(outputFile, bundleContent);
    if (!quiet) {
        console.log(`CSS bundled to ${outputFile} (${bundleContent.length} bytes)`);
    }
}

// Allow direct execution
if (process.argv[1] === fileURLToPath(import.meta.url)) {
    bundle().catch(err => {
        console.error('CSS Bundling failed:', err);
        process.exit(1);
    });
}

